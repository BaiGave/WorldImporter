#!/usr/bin/env python3
"""Build WorldImporter/EntityModelData.inc from DumpModels.java output.

  java -cp <1.21.1 client jar>:<libs>:. DumpModels models-1.21.1.json client.txt   (obfuscated jar + mappings)
  java -cp <26.3 client jar>:<libs>:.   DumpModels models-26.3.json
  python3 gen_entity_models.py models-1.21.1.json models-26.3.json > ../../WorldImporter/EntityModelData.inc

legacy = <=1.21.x geometry, modern = 26.x geometry (separate baby layers, renderer scale baked in root).
"""
import json, os, sys

def fmt(v):
    s = ("%.6f" % v).rstrip("0")
    if s.endswith("."):
        s += "0"
    return ("0.0" if s == "-0.0" else s) + "f"

def main():
    legacy, modern = json.load(open(sys.argv[1])), json.load(open(sys.argv[2]))
    dumps = {"legacy": legacy, "modern": modern}
    here = os.path.dirname(os.path.abspath(__file__))
    wanted = []
    for line in open(os.path.join(here, "layers.txt")):
        line = line.split("#", 1)[0] if line.startswith("#") else line
        parts = line.split()
        if len(parts) == 2:
            wanted.append((parts[0], parts[1]))
    polys, parts, layers = [], [], []
    for fam, lid in wanted:
        layer = dumps[fam][lid]
        start = len(parts)
        def walk(name, p, parent):
            idx = len(parts)
            poly_start = len(polys)
            for poly in p["polys"]:
                assert len(poly) == 4
                polys.append([c for v in poly for c in v])
            parts.append((name, parent, p["pose"], poly_start, len(p["polys"]), p["visible"]))
            for cname, c in p["children"].items():
                walk(cname, c, idx - start)
        walk("root", layer["root"], -1)
        layers.append((fam, lid, layer["tex"][0], layer["tex"][1], start, len(parts) - start))
    out = ["// Generated by tools/entity_models/gen_entity_models.py from vanilla LayerDefinitions",
           "// (1.21.1 client via official mappings = legacy, 26.3 client = modern). Do not edit.",
           "// Poly = 4 vertices x (x, y, z [model pixels], u, v [0..1]); parts in pre-order, parent is layer-local.",
           "#pragma once", "",
           "struct EmPart { const char* name; int parent; float pose[9]; int polyStart; int polyCount; bool visible; };",
           "struct EmLayer { const char* family; const char* id; int texW; int texH; int partStart; int partCount; };", "",
           "static const float kEmPolys[][20] = {"]
    for p in polys:
        out.append("    {" + ",".join(fmt(v) for v in p) + "},")
    out.append("};")
    out.append("static const EmPart kEmParts[] = {")
    for name, parent, pose, ps, pc, vis in parts:
        out.append('    {"%s", %d, {%s}, %d, %d, %s},' % (name, parent, ",".join(fmt(v) for v in pose), ps, pc,
                                                         "true" if vis else "false"))
    out.append("};")
    out.append("static const EmLayer kEmLayers[] = {")
    for fam, lid, tw, th, s, n in layers:
        out.append('    {"%s", "%s", %d, %d, %d, %d},' % (fam, lid, tw, th, s, n))
    out.append("};")
    print("\n".join(out))

main()

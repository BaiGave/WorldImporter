#!/usr/bin/env python3
"""Generate WorldImporter/default_block_states.inc from a vanilla data report.

  java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar --reports
  python3 tools/gen_default_block_states.py generated/reports/blocks.json 26.3

26.3+ chunk palettes store a block's default state as a bare id, so WI needs
the default property values to pick the right blockstate variant.
"""
import json, sys
src, ver = sys.argv[1], (sys.argv[2] if len(sys.argv) > 2 else "?")
blocks = json.load(open(src, encoding="utf-8"))
out = [f"// Generated by tools/gen_default_block_states.py from Minecraft {ver} blocks.json. Do not edit.",
       "// { block id, \"key:value,...\" } for blocks whose default state has properties."]
for name in sorted(blocks):
    b = blocks[name]
    if not b.get("properties"):
        continue
    d = next(s for s in b["states"] if s.get("default"))
    props = ",".join(f"{k}:{v}" for k, v in d["properties"].items())
    out.append(f'{{"{name}", "{props}"}},')
path = "WorldImporter/default_block_states.inc"
open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(path, len(out) - 2, "entries")

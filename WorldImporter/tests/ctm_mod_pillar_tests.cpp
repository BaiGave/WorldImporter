CtmPillarFace kFaces[6] = {
    CtmPillarFace::Down, CtmPillarFace::Up, CtmPillarFace::North,
    CtmPillarFace::South, CtmPillarFace::West, CtmPillarFace::East
};

void fillSame(const std::string& bits, bool same[5][5][5]) {
    require(bits.size() == 27, "neighbour field is not 27 digits");
    int i = 0;
    for (int x = -1; x <= 1; ++x)
        for (int y = -1; y <= 1; ++y)
            for (int z = -1; z <= 1; ++z) {
                const char c = bits[i++];
                require(c >= '0' && c <= '2', "neighbour digit out of range");
                // 只有 1 与中心同状态; ±2 以及未写入的格子保持 false (空气)
                same[x + 2][y + 2][z + 2] = (c == '1');
            }
}

void checkCases() {
    constexpr int n = (int)(sizeof(kCases) / sizeof(kCases[0]));
    require(n == 200, "expected 200 pillarref cases");
    for (int ci = 0; ci < n; ++ci) {
        const std::string line = kCases[ci];
        const size_t sp = line.find(' ');
        require(sp != std::string::npos, "case missing results");
        bool same[5][5][5] = {};
        fillSame(line.substr(0, sp), same);
        std::string rest = line.substr(sp + 1);
        for (int f = 0; f < 6; ++f) {
            const size_t comma = rest.find(',');
            const std::string tok = comma == std::string::npos ? rest : rest.substr(0, comma);
            require(tok.size() == 4, "face result is not 4 digits");
            const CtmPillarQuad q = DecideCtmModPillar(kFaces[f], same);
            const int expS = tok[0] - '0', expC = tok[1] - '0', expR = tok[2] - '0', expRot = tok[3] - '0';
            if (q.sprite != expS || q.col != expC || q.row != expR || q.rotation != expRot) {
                throw std::runtime_error(
                    "case " + std::to_string(ci) + " face " + std::to_string(f) +
                    " got " + std::to_string(q.sprite) + std::to_string(q.col) +
                    std::to_string(q.row) + std::to_string(q.rotation) +
                    " want " + tok);
            }
            if (comma == std::string::npos) rest.clear();
            else rest = rest.substr(comma + 1);
        }
        require(rest.empty(), "extra face results");
    }
    // 回调与数组走同一实现
    bool same[5][5][5] = {};
    fillSame(std::string(kCases[0]).substr(0, 27), same);
    const auto byArray = DecideCtmModPillar(CtmPillarFace::East, same);
    const auto byCb = DecideCtmModPillar(CtmPillarFace::East, [&](int dx, int dy, int dz) {
        if ((unsigned)(dx + 2) > 4u || (unsigned)(dy + 2) > 4u || (unsigned)(dz + 2) > 4u)
            return false;
        return same[dx + 2][dy + 2][dz + 2];
    });
    require(byArray.sprite == byCb.sprite && byArray.col == byCb.col &&
            byArray.row == byCb.row && byArray.rotation == byCb.rotation,
            "callback and array disagree");
}

// 把 WI v-up 换到 MC v-down, 套 Quad.rotate, 再换回, 对照 RotateCtmPillarUv。
void checkUvRotation() {
    auto mcRotate = [](float u, float vWi, int amount, float& ou, float& ov) {
        float um = u, vm = 1.0f - vWi;
        amount %= 4;
        if (amount < 0) amount += 4;
        float nu = um, nv = vm;
        switch (amount) {
        case 1: nu = vm; nv = 1.0f - um; break;
        case 2: nu = 1.0f - um; nv = 1.0f - vm; break;
        case 3: nu = 1.0f - vm; nv = um; break;
        default: break;
        }
        ou = nu;
        ov = 1.0f - nv;
    };
    const float samples[] = {0.0f, 0.25f, 0.5f, 1.0f, 0.2f, 1.2f, -0.1f};
    for (float u : samples) {
        for (float v : samples) {
            for (int amount = 0; amount <= 4; ++amount) {
                float eu = u, ev = v, gu = 0, gv = 0;
                RotateCtmPillarUv(eu, ev, amount);
                mcRotate(u, v, amount, gu, gv);
                if (std::fabs(eu - gu) > 1e-5f || std::fabs(ev - gv) > 1e-5f)
                    throw std::runtime_error("UV rotation disagrees with Quad.rotate");
            }
            float u1 = u, v1 = v;
            for (int i = 0; i < 4; ++i) RotateCtmPillarUv(u1, v1, 1);
            if (std::fabs(u1 - u) > 1e-5f || std::fabs(v1 - v) > 1e-5f)
                throw std::runtime_error("four quarter turns did not return to start");
        }
    }
}

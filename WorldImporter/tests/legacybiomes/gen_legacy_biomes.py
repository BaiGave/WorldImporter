#!/usr/bin/env python3
"""Emit WorldImporter/legacybiomes.inc from vanilla data-generator biome reports.

Usage:
    python3 gen_legacy_biomes.py <reports-dir>

reports-dir is the directory of per-biome JSON files, for example
dgen/1.19.2/out/reports/minecraft/worldgen/biome (63 biomes).

biome.cpp reads temperature, downfall, and effects colors. precipitation and
has_precipitation are not read, so they are left out. temperature_modifier and
grass_color_modifier are kept so the emitted JSON matches the jar shape.
"""

import json
import re
import sys
from pathlib import Path

NUMBER_RE = {
    "temperature": re.compile(r'"temperature"\s*:\s*(-?(?:\d+\.\d+|\d+))'),
    "downfall": re.compile(r'"downfall"\s*:\s*(-?(?:\d+\.\d+|\d+))'),
}

TEMP_MODS = {"none", "frozen"}
GRASS_MODS = {"none", "swamp", "dark_forest"}
REQUIRED_EFFECTS = ("sky_color", "fog_color", "water_color", "water_fog_color")


def fail(message):
    print(f"gen_legacy_biomes: {message}", file=sys.stderr)
    sys.exit(1)


def raw_number(text, key, biome_id):
    match = NUMBER_RE[key].search(text)
    if not match:
        fail(f"{biome_id}: missing numeric {key}")
    return match.group(1)


def optional_color(effects, key, biome_id):
    if key not in effects:
        return -1
    value = effects[key]
    if isinstance(value, bool) or not isinstance(value, int):
        fail(f"{biome_id}: {key} must be an int, got {value!r}")
    if value < 0:
        fail(f"{biome_id}: {key} is negative ({value}); -1 is the omit sentinel")
    return value


def load_biome(path):
    text = path.read_text(encoding="utf-8")
    data = json.loads(text)
    biome_id = path.stem
    if not isinstance(data, dict):
        fail(f"{biome_id}: root is not an object")

    effects = data.get("effects")
    if not isinstance(effects, dict):
        fail(f"{biome_id}: missing effects object")
    for key in REQUIRED_EFFECTS:
        color = optional_color(effects, key, biome_id)
        if color < 0:
            fail(f"{biome_id}: missing effects.{key}")

    temp_mod = data.get("temperature_modifier", "none")
    if temp_mod not in TEMP_MODS:
        fail(f"{biome_id}: unexpected temperature_modifier {temp_mod!r}")
    grass_mod = effects.get("grass_color_modifier", "none")
    if grass_mod not in GRASS_MODS:
        fail(f"{biome_id}: unexpected grass_color_modifier {grass_mod!r}")

    return {
        "id": biome_id,
        "temperature": raw_number(text, "temperature", biome_id),
        "downfall": raw_number(text, "downfall", biome_id),
        "temperature_modifier": temp_mod,
        "sky": effects["sky_color"],
        "fog": effects["fog_color"],
        "water": effects["water_color"],
        "water_fog": effects["water_fog_color"],
        "grass": optional_color(effects, "grass_color", biome_id),
        "foliage": optional_color(effects, "foliage_color", biome_id),
        "grass_modifier": grass_mod,
    }


def emit(biomes):
    lines = [
        "// Generated by tests/legacybiomes/gen_legacy_biomes.py — do not edit.",
        "// id, temperature, downfall, temperature_modifier, sky, fog, water, water_fog, grass(-1=omit), foliage(-1=omit), grass_color_modifier",
    ]
    for biome in biomes:
        lines.append(
            '{{"{id}", {temperature}, {downfall}, "{temperature_modifier}", '
            "{sky}, {fog}, {water}, {water_fog}, {grass}, {foliage}, "
            '"{grass_modifier}"}},'.format(**biome)
        )
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) != 2:
        fail("usage: gen_legacy_biomes.py <reports-dir>")
    reports = Path(argv[1])
    if not reports.is_dir():
        fail(f"not a directory: {reports}")

    paths = sorted(reports.glob("*.json"))
    if not paths:
        fail(f"no biome json in {reports}")

    biomes = [load_biome(path) for path in paths]
    biomes.sort(key=lambda biome: biome["id"])
    ids = [biome["id"] for biome in biomes]
    if len(ids) != len(set(ids)):
        fail("duplicate biome id")

    out = Path(__file__).resolve().parents[2] / "legacybiomes.inc"
    out.write_text(emit(biomes), encoding="utf-8")
    print(f"wrote {out} ({len(biomes)} biomes)")


if __name__ == "__main__":
    main(sys.argv)
